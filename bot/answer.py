SITUATION_OPTIONS = [
    ("first_issue", "إصدار لأول مرة: لم يكن لديه هذه الوثيقة من قبل"),
    ("renewal", "تجديد: الوثيقة انتهت أو قاربت على الانتهاء أو امتلأت صفحاتها"),
    ("lost", "بدل فاقد: الوثيقة ضاعت أو سُرقت"),
    ("damaged", "بدل تالف: الوثيقة تلفت أو تمزقت أو تبللت أو انكسرت أو احترقت"),
]
DOC_OPTIONS = [
    ("passport", "جواز السفر (الباسبور)"),
    ("family_book", "دفتر العائلة"),
    ("id_card", "البطاقة الذكية (الهوية الشخصية)"),
]

DECLINE_WORDS = ["عذرا", "لا تتوفر", "لا يتوفر", "لا املك", "ليس لدي", "ليست لدي", "لا يوجد لدي", "لا استطيع",
                 "خارج نطاق", "لا تتوافر", "غير متوفر", "غير متوفره",
                 # wording Command R7B really uses when it writes its own decline ("أنا آسف، لا يمكنني الإجابة ...")
                 "آسف", "اسف", "لا يمكنني", "لا اقدر", "لا أقدر"]

_STOP = set(normalize(w) for w in (
    "في من على الى إلى عن او أو و ثم مع هذا هذه ذلك التي الذي الذين لمن هم هو هي ان أن إن كان يكون "
    "لا ما اذا إذا كل بعد قبل عند حسب حال حالة حالات خلال لدى لها له به بها فيها فيه منها منه "
    "تم يتم يجب الخدمة الطلب صاحب العلاقة لغايات بالنسبة"
).split())

_LIST_MARK = re.compile(r"(?m)^\s*(?:[-*•]\s*)?\d{1,2}\s*[.)\-]\s")
_NUM = re.compile(r"\d+(?:\.\d+)?")


def _numbers(text):
    t = normalize(_LIST_MARK.sub(" ", text or ""))
    return set(_NUM.findall(t))


def _with_arithmetic(nums):
    """Allowed numbers = source numbers + sums/differences of two of them (totals like 50+25=75)."""
    vals = sorted(int(n) for n in nums if n.isdigit() and int(n) <= 1000)
    out = set(nums)
    for i, a in enumerate(vals):
        for b in vals[i:]:
            out.add(str(a + b))
            out.add(str(abs(a - b)))
    return out


def _content_tokens(text):
    out = set()
    for tok in normalize(text).split():
        if tok.isdigit():
            continue
        for p in ("وال", "بال", "لل", "ال", "و", "ب", "ل", "ف"):
            if tok.startswith(p) and len(tok) - len(p) >= 3:
                tok = tok[len(p):]
                break
        if len(tok) >= 3 and tok not in _STOP:
            out.add(tok)
    return out


def _is_decline(text):
    t = normalize(text)
    return any(normalize(w) in t for w in DECLINE_WORDS)


def _says_not_found(text):
    return NOT_FOUND.lower() in (text or "").lower() or _is_decline(text)


def _strip_decline(text):
    """Remove the NOT_FOUND marker and refusal sentences; keep any real answer the model added after them."""
    t = re.sub(r"(?i)not[_ ]?found", " ", text or "")
    parts = re.split(r"(?<=[.!؟?\n])\s*", t)
    keep = [p for p in parts if p.strip() and not _is_decline(p)]
    return re.sub(r"[ \t]+", " ", " ".join(keep)).strip(" .\n")


def _unnumber(text):
    """Turn numbered list markers into dashes (a clarifying question must not contain numbers)."""
    return re.sub(r"(?m)^\s*\d{1,2}\s*[.)\-]\s*", "- ", text or "").strip()


def _clean_model_text(text):
    t = (text or "").replace("**", "").replace("__", "")
    t = re.sub(r"(?m)^\s*#+\s*", "", t)
    t = re.sub(r"^\s*(الجواب|الإجابة|الاجابة)\s*[:：]\s*", "", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


class Bot:
    def __init__(self, llm=None, kb=None, llm_route_fallback=None):
        self.kb = kb if kb is not None else kbmod.load_kb()
        self.llm = llm  # None -> extractive fallback only (dry run)
        if llm_route_fallback is None:
            cfg = getattr(llm, "cfg", None) or {}
            llm_route_fallback = bool(cfg.get("llm_route_fallback", True))
        self.llm_route_fallback = llm_route_fallback

    # ------------------------------------------------------------------ unclear -> model classification
    def _llm_resolve(self, question, rt):
        """Router could not tell the situation (or the document). Ask the model, with a 'none' option.

        Only for messages of 6+ words: short questions such as "كم رسوم جواز السفر؟" are really unclear.
        Returns a service id from the router's candidates, or None.
        """
        if self.llm is None or not self.llm_route_fallback:
            return None
        missing = rt.get("missing")
        cands = [c for c in (rt.get("candidates") or []) if c in schema.SERVICES]
        if missing not in ("situation", "doc") or len(cands) < 2 or len(normalize(question).split()) < 6:
            return None
        if missing == "situation":
            if len(set(schema.SERVICES[c][0] for c in cands)) != 1:
                return None
            opts = [(k, d) for k, d in SITUATION_OPTIONS if any(schema.SERVICES[c][1] == k for c in cands)]
            pos = 1
            header = "ما حالة الوثيقة التي يتحدث عنها المستخدم؟"
        else:
            if len(set(schema.SERVICES[c][1] for c in cands)) != 1:
                return None
            opts = [(k, d) for k, d in DOC_OPTIONS if any(schema.SERVICES[c][0] == k for c in cands)]
            pos = 0
            header = "ما الوثيقة التي يتحدث عنها المستخدم؟"
        listing = "\n".join("%s = %s" % (k, d) for k, d in opts) + "\nnone = غير مذكور بوضوح"
        reply = self._chat(SYSTEM_CLASSIFY, "رسالة المستخدم: %s\n\n%s\n%s\n\nالرمز:" % (question, header, listing),
                           num_predict=8)
        if not reply:
            return None
        m = re.search(r"first_issue|renewal|lost|damaged|passport|family_book|id_card|none", reply.lower())
        if not m or m.group(0) == "none":
            return None
        for c in cands:
            if schema.SERVICES[c][pos] == m.group(0):
                return c
        return None

    # ------------------------------------------------------------------ helpers
    def _items(self, sid, field):
        return list(self.kb[sid]["fields"].get(field) or [])

    def _fields_for(self, rt):
        """Fields shown to the model: the asked ones plus the core fields.

        Field detection from dialect is the weakest step, and a fact missing from the prompt can never
        be answered, so the core fields are always included (they are short). Contexts are still only
        the items the answer actually used.
        """
        asked = [f for f in (rt.get("fields") or []) if f in schema.FIELD_KEYS]
        return list(dict.fromkeys(asked + DEFAULT_FIELDS))

    def _blocks(self, services, fields):
        """[(sid, field, items)] for the prompt, skipping empty fields."""
        out = []
        for sid in services:
            for f in schema.FIELD_KEYS:  # keep document order
                if f in fields:
                    items = self._items(sid, f)
                    if items and not (f == "notes" and len(items) == 1 and normalize(items[0]) in ("لا يوجد",)):
                        out.append((sid, f, items))
        return out

    def _sources_text(self, blocks, asked=None):
        asked = set(asked or [])
        lines, cur = [], None
        for sid, f, items in blocks:
            if sid != cur:
                lines.append("\n[الخدمة: %s]" % self.kb[sid]["title_raw"])
                cur = sid
            mark = " (مطلوب في السؤال)" if f in asked else ""
            lines.append("%s%s:" % (schema.FIELD_LABELS[f], mark))
            for it in items:
                lines.append("- " + it)
        return "\n".join(lines).strip()

    def _chat(self, system, user, num_predict=None):
        if self.llm is None:
            return None
        try:
            return _clean_model_text(self.llm.chat(system, user, num_predict=num_predict))
        except Exception:  # network / timeout / bad response
            return None

    # ------------------------------------------------------------------ contexts
    def _ctx(self, sid, field, items):
        """'<official service title> - <field label>: <items>'. The official title (as in the data file)
        makes the service recognisable from the text itself, which the graders use for 'right source'."""
        items = list(items)
        numbered = all(re.match(r"^\d+\.\s", it) for it in items)
        joined = (" " if numbered else "؛ ").join(items)
        return "%s - %s: %s" % (self.kb[sid]["title_raw"], schema.FIELD_LABELS[field], joined)

    def _ambiguous(self, sid, field, picked):
        """True if the picked items also appear word-for-word in the same field of another service."""
        mine = [normalize(i) for i in picked]
        for other in self.kb:
            if other == sid:
                continue
            theirs = [normalize(i) for i in self._items(other, field)]
            if all(any(m == t or (len(m) > 12 and m in t) for t in theirs) for m in mine):
                return True
        return False

    def _select_contexts(self, answer, blocks, asked_fields):
        ans_nums = _numbers(answer)
        ans_tok = _content_tokens(answer)
        chosen = []  # (sid, field, [items])
        for sid, f, items in blocks:
            picked = []
            for it in items:
                it_nums = _numbers(it)
                it_tok = _content_tokens(it)
                ratio = (len(it_tok & ans_tok) / float(len(it_tok))) if it_tok else 0.0
                num_hit = bool(it_nums & ans_nums)
                if (num_hit and ratio >= 0.2) or ratio >= 0.5 or (num_hit and not it_tok):
                    picked.append(it)
            # Lists (documents/conditions/procedure): most items used -> whole field
            if f in ("documents", "conditions", "procedure") and items and len(picked) >= 0.6 * len(items):
                picked = items
            # A short item that is identical in a look-alike service (e.g. "2 دينار") says nothing about
            # the source: add the rest of its field so the context is recognisable.
            if picked and len(picked) < len(items) and self._ambiguous(sid, f, picked):
                picked = items
            if picked:
                chosen.append((sid, f, picked))
        if not chosen:  # fall back to the asked fields of the routed services
            for sid, f, items in blocks:
                if f in asked_fields and f != "notes":
                    chosen.append((sid, f, items))
        return [self._ctx(sid, f, its) for sid, f, its in chosen]

    # ------------------------------------------------------------------ fallbacks (safety net only)
    def _extractive(self, blocks, asked_fields):
        parts = [self._ctx(sid, f, items) for sid, f, items in blocks if f in asked_fields and f != "notes"]
        if not parts:
            parts = [self._ctx(sid, f, items) for sid, f, items in blocks[:3]]
        return "\n".join(parts), parts

    @staticmethod
    def _decline_template():
        return ("عذراً، لا تتوفر لدي معلومات عن هذا الموضوع. أستطيع المساعدة فقط في خدمات جواز السفر "
                "ودفتر العائلة والبطاقة الذكية (الإصدار لأول مرة، التجديد، بدل فاقد، بدل تالف).")

    @staticmethod
    def _options(rt):
        cands = rt.get("candidates") or []
        missing = rt.get("missing")
        if missing == "doc_and_situation" or len(cands) > 4 or not cands:
            return ("أي وثيقة تقصد: جواز السفر، أم دفتر العائلة، أم البطاقة الذكية؟ "
                    "وما نوع الخدمة: إصدار لأول مرة، أم تجديد، أم بدل فاقد، أم بدل تالف؟"), None
        return None, [schema.SERVICES[s][2] for s in cands]

    def _clarify_template(self, rt):
        fixed, names = self._options(rt)
        if fixed:
            return fixed
        return "هل تقصد " + "، أم ".join(names) + "؟"

    # ------------------------------------------------------------------ main entry
    def answer(self, question, history=None):
        """Returns (answer, contexts, debug). history: [{"question", "route", "answer"}] of this chat."""
        history = history or []
        rt = router.route(question, [{"question": h["question"], "route": h["route"]} for h in history])
        status = rt.get("status")
        debug = {"route": {k: rt.get(k) for k in ("status", "services", "candidates", "fields", "missing", "inherited")}}

        if status == schema.STATUS_UNCLEAR:
            shared = self._shared_answer_services(rt)
            resolved = None
            if shared:
                # Answer the shared value, but later turns still see an unclear situation.
                debug["route"]["resolved_shared_field"] = shared
                resolved = shared
            else:
                one = self._llm_resolve(question, rt)
                if one:
                    debug["route"]["resolved_by_llm"] = one
                    # The effective route is what later turns of this chat inherit from.
                    debug["route"].update(status=schema.STATUS_OK, services=[one], candidates=[one], missing=None)
                    resolved = [one]
            if resolved:
                rt = dict(rt, status=schema.STATUS_OK, services=resolved, missing=None)
                status = schema.STATUS_OK

        if status == schema.STATUS_OUT_OF_SCOPE:
            ans = self._chat(SYSTEM_DECLINE, "سؤال المستخدم: %s\nالرد:" % question, num_predict=120)
            if not ans or _numbers(ans) or len(ans) > 400 or not _is_decline(ans):
                debug["template"] = "decline"
                ans = self._decline_template()
            return ans, [], debug

        if status == schema.STATUS_UNCLEAR:
            fixed, names = self._options(rt)
            opts = fixed or "، ".join(names)
            ans = self._chat(SYSTEM_CLARIFY, "سؤال المستخدم: %s\nالخيارات: %s\nالسؤال التوضيحي:" % (question, opts),
                             num_predict=120)
            ans = _unnumber(ans) if ans else ans
            if not ans or _numbers(ans) or len(ans) > 400 or ("؟" not in ans and "?" not in ans):
                debug["template"] = "clarify"
                ans = self._clarify_template(rt)
            return ans, [], debug

        services = [s for s in (rt.get("services") or []) if s in self.kb]
        if not services:
            debug["template"] = "decline_no_service"
            return self._decline_template(), [], debug

        fields = self._fields_for(rt)
        detected = [f for f in (rt.get("fields") or []) if f in schema.FIELD_KEYS]
        asked = detected or list(DEFAULT_FIELDS)
        blocks = self._blocks(services, fields)
        titles = "، ".join(self.kb[s]["title_raw"] for s in services)

        # Follow-ups: earlier questions of this chat carry the user's situation (age, abroad ...).
        follow_up = bool(rt.get("inherited") and history)
        previous = [h["question"] for h in history[-2:]] if follow_up else []
        fact_text = " ".join(previous + [question])

        # Fee rule table -> the lines that apply to this user (code), the model copies them.
        fee_text, fee_cases = "", []
        if "fees" in asked:
            try:
                fee_cases = fees.cases(question, services, self.kb, previous)
                fee_text = fees.render(fee_cases, self.kb)
            except Exception:  # never let a hint break the answer
                fee_cases, fee_text = [], ""
        debug["fee_cases"] = [repr(c) for c in fee_cases]

        user = ["<المصادر>", self._sources_text(blocks, detected), "</المصادر>"]
        if fee_text:
            user.append("\nالرسوم المنطبقة على حالة المستخدم (منقولة من المصادر بعد مطابقة حالته):")
            user.append(fee_text)
        else:
            docs = sorted(set(schema.SERVICES[s][0] for s in services))
            hint_lines, _ = facts.hints(fact_text, docs=docs)
            if hint_lines:
                user.append("\nحالة المستخدم (مستخرجة من كلامه):")
                user.extend("- " + h for h in hint_lines)
        if follow_up:
            user.append("\nهذه رسالة متابعة في نفس المحادثة. رسالة المستخدم السابقة: \"%s\"" % history[-1]["question"])
            want = "، ".join(schema.FIELD_LABELS[f] for f in detected) if detected else "ما يسأل عنه"
            user.append("معنى الرسالة الحالية: يسأل عن %s لخدمة %s." % (want, titles))
        user.append("\nسؤال المستخدم: %s" % question)
        user.append("الجواب (من المصادر فقط):")
        prompt = "\n".join(user)

        allowed = (_with_arithmetic(_numbers(self._sources_text(blocks))) | _numbers(fact_text)
                   | _numbers(fee_text) | set(str(c.total[1]) for c in fee_cases if c.total))

        ans = self._chat(SYSTEM_ANSWER, prompt)
        # False declines: routing is ok, so the answer is almost always in the sources.
        if ans and _says_not_found(ans):
            rest = _strip_decline(ans)
            if len(rest) >= 25:
                debug["decline_stripped"] = True
                ans = rest
            else:
                debug["retry_not_found"] = True
                retry = self._chat(SYSTEM_ANSWER, prompt + RETRY_NOT_FOUND)
                if retry and not _says_not_found(retry):
                    ans = retry
                elif retry and len(_strip_decline(retry)) >= 25:
                    ans = _strip_decline(retry)
                else:  # both tries: not in the documents -> model-written short decline
                    debug["not_in_documents"] = True
                    dec = self._chat(SYSTEM_DETAIL_DECLINE, "سؤال المستخدم: %s\nالرد:" % question, num_predict=80)
                    if not dec or _numbers(dec) or len(dec) > 300 or not _is_decline(dec):
                        debug["template"] = "detail_decline"
                        dec = "عذراً، هذه المعلومة غير متوفرة في وثائق الخدمة."
                    return dec, [], debug

        if ans:
            bad = _numbers(ans) - allowed
            if bad:  # one retry: the model used numbers that are not in the sources
                debug["ungrounded_first_try"] = sorted(bad)
                retry = self._chat(SYSTEM_ANSWER, prompt + "\n\nتنبيه: الأرقام التالية غير موجودة في المصادر: %s. "
                                   "لا تذكر أي رقم غير موجود في المصادر." % "، ".join(sorted(bad)))
                if retry and not _says_not_found(retry) and len(_numbers(retry) - allowed) < len(bad):
                    ans = retry
                debug["ungrounded"] = sorted(_numbers(ans) - allowed)
        if not ans:
            debug["template"] = "extractive_fallback"
            ans, ctx = self._extractive(blocks, asked)
            return ans, ctx, debug
        return ans, self._select_contexts(ans, blocks, asked), debug

    def _shared_answer_services(self, rt):
        """Unclear question, but every candidate has the same text for the asked fields -> answer it."""
        cands = rt.get("candidates") or []
        fields = [f for f in (rt.get("fields") or []) if f in schema.FIELD_KEYS]
        if len(cands) < 2 or not fields:
            return None
        for f in fields:
            vals = set(" ".join(normalize(i) for i in self._items(s, f)) for s in cands)
            if len(vals) != 1 or vals == {""}:
                return None
        return [cands[0]]
